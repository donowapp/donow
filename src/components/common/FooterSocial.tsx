export default function FooterSocial() {
  const [links, setLinks] = useState<{ icon: string; label: string; href: string }[]>([]);

  useEffect(() => {
    getPlatformSettings()
      .then((s) => {
        const out = PLATFORMS.flatMap((p) => {
          const raw = String((s as unknown as Record<string, unknown>)[p.key] ?? '').trim();
          if (!raw) return [];
          return [{ icon: p.icon, label: p.label, href: p.href(raw) }];
        });
        setLinks(out);
      })
      .catch(() => {});
  }, []);

  if (links.length === 0) return null;

  return (
    <div className="flex items-center gap-2">
      {links.map((l) => (
        <a
          key={l.label}
          href={l.href}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={l.label}
          title={l.label}
          className="flex h-9 w-9 items-center justify-center rounded-full bg-gray-800 text-gray-400 transition hover:bg-teal-600 hover:text-white"
        >
          <svg viewBox="0 0 24 24" className="h-4 w-4" fill="currentColor" aria-hidden="true">
            <path d={ICONS[l.icon]} />
          </svg>
        </a>
      ))}
    </div>
  );
}
